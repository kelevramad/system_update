# ─── Branding ──────────────────────────────────────────────────────────────


@dataclass
class ReportBranding:
	"""Visual/textual branding injected into the HTML template placeholders."""

	title: str = 'System Update Report'
	subtitle: str = ''
	company_name: str = ''
	primary_color: str = '#0066cc'
	accent_color: str = '#333333'
	background_color: str = '#f5f5f5'
	footer_text: str = 'Generated by System Update CLI'
	logo_path: str = ''
	logo_data_uri: str = field(default='', repr=False)

	def ensure_logo_loaded(self) -> None:
		"""Populate ``logo_data_uri`` from ``logo_path`` if the file exists."""
		if self.logo_data_uri or not self.logo_path:
			return
		try:
			self.logo_data_uri = load_logo_data_uri(self.logo_path)
		except Exception as e:  # pragma: no cover — defensive
			logger.warning(f'Failed to embed logo {self.logo_path}: {e}')
			self.logo_data_uri = ''


def load_logo_data_uri(path: str) -> str:
	"""Read ``path`` and return a ``data:`` URI suitable for ``<img src>``."""
	p = Path(path).expanduser()
	if not p.is_file():
		return ''
	mime, _ = mimetypes.guess_type(str(p))
	mime = mime or 'image/png'
	encoded = base64.b64encode(p.read_bytes()).decode('ascii')
	return f'data:{mime};base64,{encoded}'


def resolve_branding(
	settings: Optional[Dict] = None,
	overrides: Optional[Dict] = None,
) -> ReportBranding:
	"""Merge config ``settings['report']`` with CLI ``overrides`` into branding."""
	cfg = dict((settings or {}).get('report', {}) or {})
	brand_cfg = dict(cfg.get('branding') or {})
	if 'logo_path' in cfg and 'logo_path' not in brand_cfg:
		brand_cfg['logo_path'] = cfg['logo_path']
	for k, v in (overrides or {}).items():
		if v is not None and v != '':
			brand_cfg[k] = v
	fields = {f.name for f in ReportBranding.__dataclass_fields__.values()}
	clean = {k: v for k, v in brand_cfg.items() if k in fields}
	branding = ReportBranding(**clean)
	branding.ensure_logo_loaded()
	return branding


