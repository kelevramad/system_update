# ─── Rendering helpers ─────────────────────────────────────────────────────


_HTML_STATUS_CLASS = {
	UpdateStatus.UP_TO_DATE: 'status-up-to-date',
	UpdateStatus.UPDATE_AVAILABLE: 'status-update',
	UpdateStatus.SECURITY_UPDATE_AVAILABLE: 'status-update',
	UpdateStatus.VULNERABLE: 'status-vulnerable',
	UpdateStatus.UNKNOWN: 'status-unknown',
	UpdateStatus.ERROR: 'status-error',
}


def _html_escape(text: str) -> str:
	return (
		(text or '')
		.replace('&', '&amp;')
		.replace('<', '&lt;')
		.replace('>', '&gt;')
		.replace('"', '&quot;')
	)


def _summary_cards(stats: Dict) -> str:
	cards = [
		('', stats['total'], 'Total Packages'),
		('up-to-date', stats['up_to_date'], 'Up to Date'),
		('update-available', stats['update_available'], 'Updates Available'),
		('vulnerable', stats['vulnerable'], 'Vulnerable'),
		('unknown', stats['unknown'], 'Unknown'),
	]
	return '\n'.join(
		f'        <div class="stat">'
		f'<div class="stat-value {cls}">{val}</div>'
		f'<div class="stat-label">{label}</div></div>'
		for cls, val, label in cards
	)


def _packages_rows(apps: List[AppInfo]) -> str:
	rows: List[str] = []
	for app in apps:
		status_class = _HTML_STATUS_CLASS.get(app.update_status, 'status-unknown')
		status_text = (
			app.status_display.split(' ')[0]
			if ' ' in app.status_display
			else app.update_status.value
		)
		rows.append(
			f'            <tr>'
			f'<td><strong>{_html_escape(app.name)}</strong></td>'
			f'<td>{_html_escape(display_source(app.source))}</td>'
			f'<td>{_html_escape(app.version or "-")}</td>'
			f'<td>{_html_escape(app.latest_version or "-")}</td>'
			f'<td><span class="status {status_class}">{_html_escape(status_text)}</span></td>'
			f'</tr>'
		)
	return '\n'.join(rows)


def _vuln_section(apps: List[AppInfo], total_vulnerable: int) -> str:
	vuln_apps = [a for a in apps if a.security_findings]
	if not (vuln_apps or total_vulnerable > 0):
		return ''
	rows: List[str] = []
	for app in vuln_apps:
		for finding in app.security_findings:
			rows.append(
				f'            <tr>'
				f'<td><strong>{_html_escape(app.name)}</strong></td>'
				f'<td>{_html_escape(display_source(app.source))}</td>'
				f'<td>{_html_escape(app.version)}</td>'
				f'<td>{_html_escape(finding.get("cve", finding.get("cve_id", "N/A")))}</td>'
				f'<td><span class="status status-vulnerable">'
				f'{_html_escape(finding.get("severity", "UNKNOWN"))}</span></td>'
				f'</tr>'
			)
	return (
		'    <h2>🔥 Security Vulnerabilities Detected</h2>\n'
		'    <table>\n'
		'        <thead>\n'
		'            <tr><th>Package</th><th>Source</th><th>Version</th>'
		'<th>CVE</th><th>Severity</th></tr>\n'
		'        </thead>\n'
		'        <tbody>\n'
		+ '\n'.join(rows)
		+ '\n        </tbody>\n    </table>\n'
	)


def _security_summary_section(sec: Dict) -> str:
	if not (sec['critical'] or sec['high'] or sec['medium'] or sec['low']):
		return ''
	return (
		'    <h2>📈 Security Summary</h2>\n'
		'    <div class="summary">\n'
		f'        <div class="stat"><div class="stat-value">{sec["total_vulns"]}</div>'
		'<div class="stat-label">Total Vulns</div></div>\n'
		f'        <div class="stat"><div class="stat-value">{sec["packages_affected"]}</div>'
		'<div class="stat-label">Packages Affected</div></div>\n'
		f'        <div class="stat"><div class="stat-value">{sec["critical"]}</div>'
		'<div class="stat-label">Critical</div></div>\n'
		f'        <div class="stat"><div class="stat-value vulnerable">{sec["high"]}</div>'
		'<div class="stat-label">High</div></div>\n'
		f'        <div class="stat"><div class="stat-value update-available">{sec["medium"]}</div>'
		'<div class="stat-label">Medium</div></div>\n'
		f'        <div class="stat"><div class="stat-value unknown">{sec["low"]}</div>'
		'<div class="stat-label">Low</div></div>\n'
		'    </div>\n'
	)


def _sources_section(source_counts: Dict[str, int]) -> str:
	if not source_counts:
		return ''
	chips: List[str] = []
	for src, cnt in sorted(source_counts.items(), key=lambda kv: (-kv[1], kv[0])):
		label = display_source(src)
		key = label.lower()
		bg = _SOURCE_HEX.get(key, '#6c757d')
		fg = _source_text_color(bg)
		icon = SOURCE_ICONS.get(key, '📦')
		chips.append(
			f'        <span class="source-chip" '
			f'style="background:{bg};color:{fg};border-color:{bg};" '
			f'title="{_html_escape(label)}: {cnt} package(s)">'
			f'<span class="icon">{icon}</span>'
			f'<span class="name">{_html_escape(label)}</span>'
			f'<span class="count">{cnt}</span>'
			f'</span>'
		)
	return (
		'    <h2>📦 Sources</h2>\n'
		'    <div class="source-chips">\n'
		+ '\n'.join(chips)
		+ '\n    </div>\n'
	)


# ─── Public API ────────────────────────────────────────────────────────────


def load_template(template_path: Optional[str]) -> str:
	"""Return the template string from ``template_path`` or the built-in default."""
	if not template_path:
		return DEFAULT_HTML_TEMPLATE
	p = Path(template_path).expanduser()
	if not p.is_file():
		logger.warning(f'Template not found: {template_path} — using default.')
		return DEFAULT_HTML_TEMPLATE
	try:
		return p.read_text(encoding='utf-8')
	except Exception as e:
		logger.warning(f'Failed to read template {template_path}: {e} — using default.')
		return DEFAULT_HTML_TEMPLATE


def build_context(
	apps: List[AppInfo],
	branding: ReportBranding,
	scan_time: str,
) -> Dict[str, str]:
	"""Build the placeholder dict consumed by ``str.format`` rendering."""
	from system_update.export import get_export_stats, security_summary

	stats = get_export_stats(apps)
	sec = security_summary(apps)

	logo_html = (
		f'<img class="logo" src="{branding.logo_data_uri}" alt="logo">'
		if branding.logo_data_uri
		else ''
	)
	subtitle_html = (
		f'<div class="subtitle">{_html_escape(branding.subtitle)}</div>'
		if branding.subtitle
		else ''
	)
	company_html = (
		f'<div class="company">{_html_escape(branding.company_name)}</div>'
		if branding.company_name
		else ''
	)

	return {
		'title': _html_escape(branding.title),
		'scan_time': _html_escape(scan_time),
		'subtitle_html': subtitle_html,
		'company_html': company_html,
		'logo_html': logo_html,
		'footer_text': _html_escape(branding.footer_text),
		'primary_color': branding.primary_color,
		'accent_color': branding.accent_color,
		'background_color': branding.background_color,
		'summary_cards': _summary_cards(stats),
		'packages_rows': _packages_rows(apps),
		'vuln_section': _vuln_section(apps, stats['vulnerable']),
		'security_summary_section': _security_summary_section(sec),
		'sources_section': _sources_section(stats['source_counts']),
	}


class _SafeDict(dict):
	"""Dict that returns ``{key}`` for missing placeholders so unknown tokens are preserved."""

	def __missing__(self, key: str) -> str:  # pragma: no cover — trivial
		return '{' + key + '}'


def render_html(
	apps: List[AppInfo],
	branding: Optional[ReportBranding] = None,
	template_path: Optional[str] = None,
	scan_time: Optional[str] = None,
) -> str:
	"""Render the full HTML report with ``branding`` into the template text."""
	from datetime import datetime

	branding = branding or ReportBranding()
	branding.ensure_logo_loaded()
	scan_time = scan_time or datetime.now().strftime('%Y-%m-%d %H:%M:%S')
	template = load_template(template_path)
	ctx = build_context(apps, branding, scan_time)
	try:
		return template.format_map(_SafeDict(ctx))
	except Exception as e:
		logger.error(f'Template render failed ({e}); falling back to default.')
		return DEFAULT_HTML_TEMPLATE.format_map(_SafeDict(ctx))


