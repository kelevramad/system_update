def _source_text_color(hex_bg: str) -> str:
	"""Pick black or white text based on background luminance."""
	h = hex_bg.lstrip('#')
	if len(h) != 6:
		return '#ffffff'
	try:
		r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
	except ValueError:
		return '#ffffff'
	# Perceptual luminance — light bg → dark text.
	luma = (0.299 * r + 0.587 * g + 0.114 * b) / 255
	return '#222222' if luma > 0.6 else '#ffffff'

